export const getCoursesByProdiAndSemester = (
  prodi: string,
  semester: number
): string[] => {
  return COURSES_BY_PRODI_AND_SEMESTER[prodi]?.[semester] ?? [];
};

export const COURSES_BY_PRODI: Record<string, string[]> = Object.keys(
  COURSES_BY_PRODI_AND_SEMESTER
).reduce((acc, prodi) => {
  const semesterCourses = Object.values(
    COURSES_BY_PRODI_AND_SEMESTER[prodi] ?? {}
  ).flat();
  const electives = ELECTIVE_COURSES_BY_PRODI[prodi] ?? [];
  acc[prodi] = Array.from(new Set([...semesterCourses, ...electives]));
  return acc;
}, {} as Record<string, string[]>);

export const getCoursesByProdi = (prodi: string): string[] => {
  const courses = COURSES_BY_PRODI[prodi] ?? [];
  return Array.from(new Set(courses)).sort((a, b) => a.localeCompare(b));
};
